export function pstLookup(type, r, c, sideRed) {
  const table = TABLES[type];
  if (!table) return 0;
  const rr = sideRed ? r : 9 - r;
  const cc = sideRed ? c : 8 - c;
  return table[rr]?.[cc] || 0;
}
